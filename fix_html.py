for path in root.glob('*.html'):
    if path.name == 'index.html':
        continue
    
    text = path.read_text(encoding='utf-8')
    new_text = text
    
    # 各ファイルの説明文を置き換える
    if path.name in explanations:
        new_explanation = explanations[path.name]
        # 最初のonclick="yomu('...')を置き換える
        pattern = r"onclick=\"yomu\('([^']*)'\)"
        # より柔軟な正規表現を使用
        pattern = r"onclick=\"yomu\('(.+?)'\)\""
        new_text = re.sub(pattern, f"onclick=\"yomu('{new_explanation}')\"", new_text, count=1)
    
    if new_text != text:
        path.write_text(new_text, encoding='utf-8')
        print(f'updated {path.name}')
    else:
        print(f'no match for {path.name}')

print('done')
